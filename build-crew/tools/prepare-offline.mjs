// Regenerates offline.js, the service worker's precache list: the page shell plus every module reachable from
// src/main.js through relative imports (including the shared Spell Jump modules and dynamic imports). Run it after
// adding, moving or removing a module, then bump VERSION in sw.js. Developer-only: the output is committed, so
// neither deploy nor play needs this script.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'),
  game = path.join(root, 'build-crew'),
  lab = path.join(root, 'lab') + path.sep,
  files = new Set();
// Adds a file, and for a script every file it imports, to `set`. The Lab (/lab/) is optional: the first pass stops at
// its door so the game's own shell never needs it, and a second pass lists what the Lab brings along separately.
function visit(file, set = files, stopAtLab = true) {
  if (set.has(file) || (stopAtLab && file.startsWith(lab))) return;
  set.add(file);
  if (!/\.(m?js)$/.test(file) || file.includes('/vendor/')) return;
  const s = readFileSync(file, 'utf8');
  for (const m of s.matchAll(/(?:from\s*|import\s*\(\s*|import\s*)['"]([^'"]+)['"]/g)) {
    if (m[1].startsWith('.')) visit(path.resolve(path.dirname(file), m[1]), set, stopAtLab);
  }
}
for (const f of [
  'index.html',
  'style.css',
  'celebrate.css',
  'shell.css',
  'vendor/fonts/russo-one-400.woff2',
  'vendor/fonts/barlow-semi-condensed-600.woff2',
  'vendor/fonts/barlow-semi-condensed-700.woff2',
  'vendor/fonts/barlow-semi-condensed-800.woff2',
  'manifest.webmanifest',
  'icons/icon.svg',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'src/main.js',
])
  visit(path.join(game, f));
const shell = ['./', ...Array.from(files, (f) => path.relative(game, f)).sort()];
// The Lab's modules (lab/src/index.js and what it loads), cached when they can be fetched and never required.
const labFiles = new Set();
visit(path.join(root, 'lab/src/index.js'), labFiles, false);
const optional = Array.from(labFiles, (f) => path.relative(game, f))
  .filter((f) => !shell.includes(f))
  .sort();
const header = '// Generated by tools/prepare-offline.mjs; all source modules remain shared live imports.';
writeFileSync(
  path.join(game, 'offline.js'),
  `${header}\nconst SHELL = ${JSON.stringify(shell, null, 2)};\n` +
    `// Optional: the Lab (/lab/). A missing, blocked or older Lab never stops the game from installing.\n` +
    `const OPTIONAL = ${JSON.stringify(optional, null, 2)};\n`,
);
console.log(`${files.size} offline files, ${optional.length} optional Lab files`);
